"""launchd (LaunchAgent) scheduler for macOS.

StartCalendarInterval fires at the configured time and, if the Mac was
asleep, launchd runs the job on wake. RunAtLoad covers login/boot after
the machine was powered off. `tuner schedule run` is idempotent, so extra
invocations are harmless and missed periods are generated by catch-up.
"""

from __future__ import annotations

import os
import plistlib
import subprocess
from pathlib import Path

from tuner import paths
from tuner.fsutil import atomic_write_bytes
from tuner.scheduler.base import Spec

LABEL = "com.tuner.report"


def plist_path() -> Path:
    """LaunchAgent plist location."""
    return paths.user_home() / "Library" / "LaunchAgents" / f"{LABEL}.plist"


def render_plist(spec: Spec, argv: list[str], log_dir: Path) -> bytes:
    """Build the LaunchAgent plist."""
    cal: dict[str, int] = {"Hour": spec.hour, "Minute": spec.minute}
    if spec.period == "weekly":
        cal["Weekday"] = spec.weekday
    elif spec.period == "monthly":
        cal["Day"] = spec.day_of_month
    body = {
        "Label": LABEL,
        "ProgramArguments": [*argv, "schedule", "run"],
        "StartCalendarInterval": cal,
        "RunAtLoad": True,
        "LowPriorityIO": True,
        "StandardOutPath": str(log_dir / "schedule.out.log"),
        "StandardErrorPath": str(log_dir / "schedule.err.log"),
    }
    return plistlib.dumps(body)


def _launchctl(*args: str) -> subprocess.CompletedProcess:
    """Run launchctl, capturing output (skipped under TUNER_FAKE_HOME)."""
    if os.environ.get("TUNER_FAKE_HOME"):  # tests must not touch the OS
        return subprocess.CompletedProcess(args, 0, "", "")
    return subprocess.run(["launchctl", *args], capture_output=True,
                          text=True, check=False)


class LaunchdScheduler:
    """Manage the Tuner LaunchAgent."""

    def _domain(self) -> str:
        """launchd GUI domain for this user."""
        return f"gui/{os.getuid()}"

    def install(self, spec: Spec, argv: list[str]) -> str:
        """Write the plist and (re)load it. Returns the plist path."""
        log_dir = paths.ensure_private_dir(paths.data_dir() / "logs")
        path = plist_path()
        atomic_write_bytes(path, render_plist(spec, argv, log_dir),
                           private=False)
        _launchctl("bootout", f"{self._domain()}/{LABEL}")
        res = _launchctl("bootstrap", self._domain(), str(path))
        if res.returncode != 0 and "already" not in res.stderr.lower():
            raise RuntimeError(f"launchctl bootstrap failed: "
                               f"{res.stderr.strip()}")
        return str(path)

    def uninstall(self) -> bool:
        """Unload and delete the plist; True if something was removed."""
        path = plist_path()
        _launchctl("bootout", f"{self._domain()}/{LABEL}")
        if path.exists():
            path.unlink()
            return True
        return False

    def status(self) -> dict:
        """Installed/loaded state."""
        path = plist_path()
        loaded = _launchctl("print", f"{self._domain()}/{LABEL}"
                            ).returncode == 0
        return {"supported": True, "installed": path.exists(),
                "loaded": loaded, "path": str(path), "label": LABEL}
